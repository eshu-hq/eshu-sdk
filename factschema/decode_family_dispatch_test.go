func decodeEnvelopeByKind(t *testing.T, env Envelope) error {
	t.Helper()
	decode, ok := decoderByKind[env.FactKind]
	if !ok || decode == nil {
		t.Fatalf("no public decoder registered for fact kind %q", env.FactKind)
	}
	return decode(env)
}

func decodeByKind(t *testing.T, factKind string, payload map[string]any) error {
	t.Helper()
	env := Envelope{FactKind: factKind, SchemaVersion: "1.0.0", Payload: payload}
	return decodeEnvelopeByKind(t, env)
}
