package entrypoints

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

// GeneratedFile is a path relative to a command directory and its exact bytes.
type GeneratedFile struct {
	Name     string
	Contents []byte
}

// Generate renders one deterministic Go main for a validated manifest.
func Generate(m Manifest) ([]GeneratedFile, error) {
	if err := validateManifest(m); err != nil {
		return nil, err
	}
	quoted := make([]string, len(m.SupportedProtocols))
	for i, protocol := range m.SupportedProtocols {
		quoted[i] = strconv.Quote(protocol)
	}
	source := fmt.Sprintf(mainTemplate, strconv.Quote(m.HandlerImportPath), m.HandlerFunc, strings.Join(quoted, ", "), m.MaxRequestBytes, m.MaxResultBytes)
	contents, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("format generated command: %w", err)
	}
	return []GeneratedFile{{Name: "main.go", Contents: contents}}, nil
}

const mainTemplate = `// SPDX-License-Identifier: MIT
// Copyright (c) 2025-2026 eshu-hq

// Code generated by collector-entrypoints-gen; DO NOT EDIT.
// Source: the provider-owned entrypoint manifest.

package main

import (
 "context"
 "flag"
 "fmt"
 "io"
 "os"
 "os/signal"
 "syscall"

 "github.com/eshu-hq/eshu-sdk/collector/command"
 provider %s
)

func main() {
 defer func() {
  if recover() != nil {
   os.Stderr.WriteString("collector command failed: panic\n")
   os.Exit(1)
  }
 }()
 flags := flag.NewFlagSet("collector", flag.ContinueOnError)
 flags.SetOutput(io.Discard)
 stdio := flags.Bool("sdk-stdio", false, "serve one collector request over stdio")
 if err := flags.Parse(os.Args[1:]); err != nil || !*stdio || flags.NArg() != 0 { os.Stderr.WriteString("collector command failed: flags\n"); os.Exit(2) }
 ctx, cancel := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
 defer cancel()
 if err := command.Run(ctx, os.Stdin, os.Stdout, provider.%s, command.Options{
  SupportedProtocols: []string{%s},
  MaxRequestBytes: %d,
  MaxResultBytes: %d,
 }); err != nil {
  fmt.Fprintln(os.Stderr, err)
  os.Exit(1)
 }
}
`
